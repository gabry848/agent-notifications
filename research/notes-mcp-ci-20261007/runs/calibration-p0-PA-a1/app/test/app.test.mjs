function fixture(t) {const dir=mkdtempSync(join(tmpdir(),'quick-notes-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));return join(dir,'nested','notes.sqlite');}
test('storage validation, atomicity, literal search, pagination and persistence',t=>{
  const path=fixture(t);let s=openStore(path);
  const a=s.createNote('  A 100%_ note  ',[' WORK ','work','z']);
  assert.deepEqual(a.tags,['work','z']);assert.equal(a.text,'A 100%_ note');
  s.createNote('second',['other']);
  assert.equal(s.listNotes({q:'100%_'}).length,1);
  assert.equal(s.listNotes({q:'a 100',tag:' WORK '})[0].id,a.id);
  assert.equal(s.listNotes({limit:1,offset:1})[0].id,a.id);
  for(const tags of [['ok',null],[''],['x'.repeat(41)],'work']) assert.throws(()=>s.createNote('bad',tags));
  assert.throws(()=>s.updateNote(a.id,{text:'changed',tags:['']}));
  assert.deepEqual(s.getNote(a.id),a);
  assert.throws(()=>s.importNotes([{text:'valid'},{text:' '} ]));
  assert.equal(s.listNotes().length,2);
  const b=s.updateNote(a.id,{tags:['home']});assert.equal(b.createdAt,a.createdAt);assert.ok(b.updatedAt>a.updatedAt);
  assert.deepEqual(s.listTags(),[{name:'home',count:1},{name:'other',count:1}]);
  assert.equal(s.updateNote(999,{}),null);assert.equal(s.deleteNote(999),false);
  assert.equal(s.deleteNote(a.id),true);assert.deepEqual(s.listTags(),[{name:'other',count:1}]);
  s.close();s=openStore(path);assert.equal(s.listNotes()[0].text,'second');s.close();
});
test('MCP real stdio roundtrip and restart',async t=>{
  const path=fixture(t);
  const run=async lines=>{
    const child=spawn(process.execPath,['src/mcp.mjs','--db',path],{stdio:['pipe','pipe','pipe']});
    const output=[];let stderr='';child.stderr.on('data',c=>stderr+=c);
    createInterface({input:child.stdout}).on('line',line=>output.push(JSON.parse(line)));
    const exited=once(child,'exit');child.stdin.end(lines.join('\n')+'\n');
    const [code]=await exited;assert.equal(code,0,stderr);return output;
  };
  const rpc=(id,method,params)=>JSON.stringify({jsonrpc:'2.0',id,method,params});
  const out=await run(['', '{bad', JSON.stringify({jsonrpc:'2.0',method:'notifications/initialized'}),rpc(1,'initialize',{}),rpc(2,'tools/list'),rpc(3,'tools/call',{name:'notes_create',arguments:{text:'hello',tags:['Work']}}),rpc(4,'tools/call',{name:'notes_import',arguments:{notes:[{text:'fine'},{text:''}]}}),rpc(5,'resources/read',{uri:'notes://all'}),rpc(6,'missing')]);
  assert.equal(out.length,7);assert.equal(out[0].error.code,-32700);
  assert.equal(out[1].result.protocolVersion,'2024-11-05');assert.equal(out[2].result.tools.length,8);
  assert.deepEqual(JSON.parse(out[3].result.content[0].text).tags,['work']);
  assert.equal(out[4].result.isError,true);
  const resource=JSON.parse(out[5].result.contents[0].text);
  assert.ok(Array.isArray(resource));assert.equal(resource.length,1);assert.equal(resource[0].id,1);
  assert.equal(out[6].error.code,-32601);
  const persisted=await run([rpc('next','tools/call',{name:'notes_get',arguments:{id:1}})]);
  assert.equal(JSON.parse(persisted[0].result.content[0].text).text,'hello');
  const many=await run([rpc(10,'tools/call',{name:'notes_import',arguments:{notes:Array.from({length:105},(_,i)=>({text:`bulk ${i}`}))}}),rpc(11,'resources/read',{uri:'notes://all'}),rpc(12,'tools/call',{name:'notes_export',arguments:{}})]);
  assert.equal(JSON.parse(many[1].result.contents[0].text).length,106);
  const exported=JSON.parse(many[2].result.content[0].text);
  assert.equal(exported.version,1);assert.equal(exported.notes.length,106);assert.equal(exported.notes[0].text,'hello');
});
test('web dashboard, forms, API validation and persistence',async t=>{
  const path=fixture(t);
  const child=spawn(process.execPath,['src/web.mjs','--db',path,'--port','0'],{stdio:['ignore','pipe','pipe']});
  const exited=once(child,'exit');let stderr='';child.stderr.on('data',c=>stderr+=c);
  t.after(async()=>{child.kill();await exited;});
  const lines=createInterface({input:child.stdout});
  const [line]=await once(lines,'line');const base=`http://127.0.0.1:${JSON.parse(line).port}`;
  const request=(path,method='GET',data)=>fetch(base+path,{method,headers:{'Content-Type':'application/json'},...(data?{body:JSON.stringify(data)}:{}),redirect:'manual'});
  let res=await request('/api/notes','POST',{text:'<script>alert(1)</script>',tags:['Work']});assert.equal(res.status,201,stderr);const note=await res.json();
  const html=await (await request('/')).text();assert.ok(html.includes('&lt;script&gt;'));assert.ok(!html.includes('<script>'));assert.ok(html.includes('work (1)'));
  assert.equal((await request(`/notes/${note.id}/edit`)).status,200);
  res=await fetch(base+'/notes',{method:'POST',body:new URLSearchParams({text:'from form',tags:'One, TWO'}),redirect:'manual'});assert.equal(res.status,303);assert.equal(res.headers.get('location'),'/');
  assert.equal((await request('/api/notes?limit=0')).status,400);
  assert.equal((await request('/api/notes/999')).status,404);
  assert.equal((await request('/api/import','POST',{notes:[{text:'valid'},{text:''}]})).status,400);
  assert.equal((await (await request('/api/export')).json()).notes.length,2);
  res=await request(`/api/notes/${note.id}`,'PATCH',{text:'updated',tags:[]});assert.equal((await res.json()).text,'updated');
  assert.equal((await request(`/api/notes/${note.id}`,'DELETE')).status,200);
  assert.equal((await request(`/api/notes/${note.id}`)).status,404);
  const imported=await (await request('/api/import','POST',{notes:Array.from({length:21},(_,i)=>({text:`page note ${i}`,tags:['paging']}))})).json();
  const page2=await (await request('/?tag=PAGING&page=2')).text();assert.ok(page2.includes('page note 0'));assert.ok(page2.includes('Previous'));assert.ok(!page2.includes('page note 20'));
  res=await fetch(base+`/notes/${imported[0].id}`,{method:'POST',body:new URLSearchParams({text:'form updated',tags:'Edited'}),redirect:'manual'});assert.equal(res.status,303);
  assert.deepEqual((await (await request(`/api/notes/${imported[0].id}`)).json()).tags,['edited']);
  res=await fetch(base+`/notes/${imported[0].id}/delete`,{method:'POST',redirect:'manual'});assert.equal(res.status,303);
  const badForm=await fetch(base+'/notes',{method:'POST',body:new URLSearchParams({text:'   ',tags:''})});assert.equal(badForm.status,400);assert.ok((await badForm.text()).includes('role="alert"'));
  child.kill();await exited;
  const s=openStore(path);assert.equal(s.listNotes({q:'from form'}).length,1);assert.equal(s.listNotes().length,21);s.close();
});

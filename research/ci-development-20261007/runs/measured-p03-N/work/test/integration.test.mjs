import test from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import {mkdtemp, readFile, writeFile, readdir, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createCatalog} from '../src/catalog.mjs';
import {createServer} from '../src/server.mjs';
const record = {id: 'a/b café', name: 'Café', version: '1.2.0', tags: ['web'], dependencies: []};
test('HTTP CRUD, encoded ids, exports, transactional imports and error recovery', async t => {
  const catalog = createCatalog(), server = createServer(catalog);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, method = 'GET', body) => fetch(base + path, {method, ...(body === undefined ? {} : {body})});
  assert.deepEqual(await (await request('/health')).json(), {ok: true});
  assert.equal((await request('/records', 'POST', JSON.stringify(record))).status, 201);
  assert.equal((await request('/records', 'POST', JSON.stringify(record))).status, 409);
  const route = '/records/' + encodeURIComponent(record.id);
  assert.deepEqual(await (await request(route)).json(), record);
  assert.equal((await request(route, 'PATCH', '{broken')).status, 400);
  assert.equal((await request(route, 'PATCH', '{"name":"Updated"}')).status, 200);
  assert.equal((await (await request('/records?tags=WEB&versionMin=1.0.0')).json()).total, 1);
  assert.equal((await request('/records?offset=')).status, 400);
  const csv = await (await request('/export.csv')).text(); assert.ok(csv.startsWith('id,name,version,tags,dependencies'));
  assert.equal((await request('/import.csv', 'POST', csv)).status, 409);
  const ndjson = await (await request('/export.ndjson')).text(); assert.equal(JSON.parse(ndjson).name, 'Updated');
  assert.equal((await request('/import.ndjson', 'POST', JSON.stringify({...record, id: 'new'}) + '\n{}')).status, 400);
  assert.equal(catalog.get('new'), null);
  const large = await request('/records', 'POST', 'x'.repeat(1024 * 1024 + 1));
  assert.equal(large.status, 413); assert.equal(typeof (await large.json()).error, 'string');
  assert.equal((await request('/records/%ZZ')).status, 400);
  assert.equal((await request('/plan?ids=missing')).status, 400);
  assert.equal((await request('/unknown')).status, 404);
  assert.equal((await request(route, 'DELETE')).status, 204);
  assert.equal((await request(route)).status, 404);
  assert.equal((await request('/health')).status, 200);
});
test('CLI persistence and failed writes preserve bytes without leftover temporary files', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'catalog-test-')); t.after(() => rm(dir, {recursive: true, force: true}));
  const file = join(dir, 'catalog.json');
  const cli = (...args) => spawnSync(process.execPath, ['src/cli.mjs', ...args, '--file', file], {encoding: 'utf8'});
  assert.equal(JSON.parse(cli('list').stdout).total, 0);
  assert.equal(cli('add', '--record', JSON.stringify(record)).status, 0);
  const before = await readFile(file, 'utf8');
  for (const args of [['add', '--record', JSON.stringify(record)], ['add', '--record', '{}'], ['remove'], ['plan', '--ids', 'missing'], ['list', '--unknown', 'yes']]) {
    const result = cli(...args); assert.notEqual(result.status, 0); assert.ok(result.stderr);
    assert.equal(await readFile(file, 'utf8'), before);
  }
  const input = join(dir, 'input.csv');
  await writeFile(input, 'id,name,version,tags,dependencies\nnew,New,1.0.0,,\nbad,Bad,invalid,,');
  assert.notEqual(cli('import-csv', '--input', input).status, 0);
  assert.equal(await readFile(file, 'utf8'), before);
  assert.deepEqual(JSON.parse(cli('plan', '--ids', record.id).stdout), {ids: [record.id]});
  assert.ok(cli('export-csv').stdout.startsWith('id,name,version,tags,dependencies'));
  assert.equal(JSON.parse(cli('list', '--tags', ' WEB ').stdout).total, 1);
  assert.equal(cli('remove', '--id', record.id).status, 0);
  assert.deepEqual(JSON.parse(await readFile(file, 'utf8')), []);
  assert.deepEqual((await readdir(dir)).sort(), ['catalog.json', 'input.csv']);
});
